import test from 'node:test';import assert from 'node:assert/strict';
import {FirstABResearch,studyBQuality,TWO_HOURS} from '../src/cohorts.js';
import {HourAudit} from '../src/hour-audit.js';
import {makeServer} from '../src/server.js';
const T=1_797_000_000_000; // exactly minute-aligned
const ev=(s,t,signal,p=1)=>({symbol:s,timeframe:'1m',barClosedAtMs:t,price:p,id:`${s}:1m:${t}:${signal}`,signal});
const C=t=>({endMs:Math.floor(t/300000)*300000,close:1.1,ma7:1,ma25:.9,rsi:55});
const sym='DOODUSDT';
test('A1 is silent, and no A can publish',()=>{const x=new FirstABResearch({clock:()=>T+TWO_HOURS});
  assert.equal(x.ingest(ev(sym,T,'LONG_A'),{warmVerified:true}).status,'A1_STORED_SILENTLY');
  assert.equal(x.summary().sendsFCM,false);assert.equal(x.summary().entersHome,false);
  assert.equal(x.ingest(ev(sym,T+60000,'LONG_A')).status,'IGNORE_SUBSEQUENT_A');
  assert.equal(x.rows.length,1);
});
test('rejected B1 then valid B2 = one provisional selection; suppress all further B',()=>{
  const x=new FirstABResearch({clock:()=>T+TWO_HOURS});
  x.ingest(ev(sym,T,'LONG_A'),{warmVerified:true});
  assert.equal(x.ingest(ev(sym,T+60000,'PROTECT')).status,'PROTECT_OBSERVED_SILENTLY');
  assert.equal(x.ingest(ev(sym,T+120000,'LONG_B',1.25),C(T+120000)).status,'B1_REJECTED_RESEARCH');
  x.ingest(ev(sym,T+180000,'PROTECT'));
  assert.equal(x.ingest(ev(sym,T+240000,'LONG_B',1.05),C(T+240000)).status,'B2_SELECTED_RESEARCH_ONLY');
  x.ingest(ev(sym,T+300000,'PROTECT'));
  assert.equal(x.ingest(ev(sym,T+360000,'LONG_B',1.06),C(T+360000)).status,'IGNORE_B3_PLUS');
  assert.equal(x.rows[0].selected.number,2);assert.equal(x.rows[0].selected.publicationAuthorized,false);
  assert.equal(x.summary().selectedAtB2,1);
});
test('valid B1 excludes B2 notifications',()=>{const x=new FirstABResearch({clock:()=>T+TWO_HOURS});
 x.ingest(ev(sym,T,'LONG_A'),{warmVerified:true});
 x.ingest(ev(sym,T+60000,'PROTECT'));
 assert.equal(x.ingest(ev(sym,T+120000,'LONG_B',1.02),C(T+120000)).status,'B1_SELECTED_RESEARCH_ONLY');
 x.ingest(ev(sym,T+180000,'PROTECT'));
 assert.equal(x.ingest(ev(sym,T+240000,'LONG_B',1.03),C(T+240000)).status,'SUPPRESS_ALREADY_SELECTED');
 assert.equal(x.summary().selectedAtB1,1);
});
test('two-hour expiration and no long B with no A',()=>{const x=new FirstABResearch({clock:()=>T+TWO_HOURS+180000});
 assert.equal(x.ingest(ev(sym,T+60000,'LONG_B')).status,'NO_ACTIVE_A');
 x.ingest(ev(sym,T,'LONG_A'),{warmVerified:true});
 assert.equal(x.ingest(ev(sym,T+TWO_HOURS+60000,'LONG_B',1.02),C(T+TWO_HOURS+60000)).status,'NO_ACTIVE_A');
 assert.equal(x.rows[0].status,'INCOMPLETE'); // No candle coverage for full two hours; cannot score as completed.
});
test('cold start and unverified first A always refused',()=>{const x=new FirstABResearch({clock:()=>T+100000});
 assert.equal(x.ingest(ev(sym,T,'LONG_A')).status,'REJECT_COLD_OR_UNPROVEN_FIRST_A');
 assert.equal(x.rows.length,0);
});
test('no time travel, incorrect IDs, 5m context stale, or chase',()=>{const x=new FirstABResearch({clock:()=>T+600000});
 assert.equal(x.ingest(ev(sym,T+660000,'LONG_A'),{warmVerified:true}).status,'REJECT_FUTURE');
 const bad={...ev(sym,T,'LONG_A'),id:'other'};
 assert.equal(x.ingest(bad,{warmVerified:true}).status,'REJECT_INVALID_OR_UNCLOSED');
 x.ingest(ev(sym,T,'LONG_A'),{warmVerified:true});
 assert.equal(studyBQuality(ev(sym,T+60000,'LONG_B',1.02),x.rows[0],C(T-600000)).passed,false);
 assert.equal(studyBQuality(ev(sym,T+60000,'LONG_B',1.4),x.rows[0],C(T+60000)).reason,'B_PRICE_ALREADY_TOO_FAR');
});
test('duplicate event and per-symbol isolation',()=>{const x=new FirstABResearch({clock:()=>T+600000});
 x.ingest(ev(sym,T,'LONG_A'),{warmVerified:true});
 assert.equal(x.ingest(ev(sym,T,'LONG_A'),{warmVerified:true}).status,'DUPLICATE');
 assert.equal(x.ingest(ev('JCTUSDT',T+60000,'LONG_B',1.01),C(T+60000)).status,'NO_ACTIVE_A');
});
test('OUT_FINAL closes episode; a later A can restart',()=>{const x=new FirstABResearch({clock:()=>T+600000});
 x.ingest(ev(sym,T,'LONG_A'),{warmVerified:true});
 assert.equal(x.ingest(ev(sym,T+60000,'OUT_FINAL',.98)).status,'EPISODE_CLOSED');
 assert.equal(x.ingest(ev(sym,T+120000,'LONG_A'),{warmVerified:true}).status,'A1_STORED_SILENTLY');
 assert.equal(x.rows.length,2);
});
test('LONG B without a PROTECT is not accepted',()=>{const x=new FirstABResearch({clock:()=>T+600000});
  x.ingest(ev(sym,T,'LONG_A'),{warmVerified:true});
  assert.equal(x.ingest(ev(sym,T+60000,'LONG_B',1.02),C(T+60000)).status,'REJECT_B_WITHOUT_NEW_PROTECT');
  assert.equal(x.rows[0].bCount,0);
});
